"""Bakes tools/blockbench/furioso.bbmodel into client/arsenal/FuriosoAnims.java.

Edit the moves in Blockbench (Animate tab; 1 s on the timeline = 20 Furioso script ticks), save the .bbmodel, then:
    python tools/bbmodel_to_furioso.py
Only rotation keyframes are read. Blockbench -> Java axis mapping: x and y negated, z as-is (same as the Fluffy
Mimic converter).
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "blockbench", "furioso.bbmodel")
OUT = os.path.join(HERE, "..", "src", "main", "java", "com", "slop", "projectminecraft", "client", "arsenal", "FuriosoAnims.java")

BONES = ["body", "head", "right_arm", "left_arm", "right_leg", "left_leg"]
ORDER = ["pistols", "lance", "hammer", "katana", "gauntlets", "knife", "axe", "mace", "greatsword", "shortswords", "shotgun", "durandal"]


def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def main():
    with open(SRC, encoding="utf-8") as f:
        model = json.load(f)
    by_name = {a["name"]: a for a in model.get("animations", [])}
    lines = []
    for name in ORDER:
        a = by_name.get(name)
        bones = {b: [] for b in BONES}
        if a:
            for an in a.get("animators", {}).values():
                bone = an.get("name")
                if bone not in bones:
                    continue
                for kf in an.get("keyframes", []):
                    if kf.get("channel") != "rotation":
                        continue
                    dp = kf["data_points"][0]
                    t = kf["time"] * 20
                    bones[bone].append((t, -num(dp.get("x")), -num(dp.get("y")), num(dp.get("z"))))
        anim = []
        for b in BONES:
            keys = sorted(bones[b])
            flat = ", ".join(f"{t:g}f, {x:g}f, {y:g}f, {z:g}f" for t, x, y, z in keys)
            anim.append(f"            {{{flat}}}")
        lines.append(f"        // {name}\n        {{\n" + ",\n".join(anim) + "\n        }")
    body = ",\n".join(lines)
    java = f"""package com.slop.projectminecraft.client.arsenal;

/**
 * GENERATED by tools/bbmodel_to_furioso.py from tools/blockbench/furioso.bbmodel: do not edit by hand.
 * Rotation keyframes per Furioso weapon and bone, in script ticks from the start of the weapon's beat and Java model
 * degrees. Each row is flat: time, x, y, z, time, x, y, z...
 */
public final class FuriosoAnims {{
    private FuriosoAnims() {{}}

    public static final int BODY = 0, HEAD = 1, RIGHT_ARM = 2, LEFT_ARM = 3, RIGHT_LEG = 4, LEFT_LEG = 5;

    static final float[][][] KEYS = {{
{body}
    }};

    /** Rotation (degrees) of a bone at time t into a weapon's beat, or null if that bone isn't animated. */
    public static float[] sample(int weapon, int bone, double t) {{
        if (weapon < 0 || weapon >= KEYS.length) return null;
        float[] k = KEYS[weapon][bone];
        if (k.length == 0) return null;
        int n = k.length / 4;
        if (t <= k[0]) return new float[]{{k[1], k[2], k[3]}};
        for (int i = 0; i < n - 1; i++) {{
            float t0 = k[i * 4], t1 = k[(i + 1) * 4];
            if (t > t1) continue;
            double u = (t - t0) / Math.max(1e-4, t1 - t0);
            u = u * u * (3 - 2 * u);
            float[] r = new float[3];
            for (int c = 0; c < 3; c++) r[c] = (float) (k[i * 4 + 1 + c] + (k[(i + 1) * 4 + 1 + c] - k[i * 4 + 1 + c]) * u);
            return r;
        }}
        return new float[]{{k[(n - 1) * 4 + 1], k[(n - 1) * 4 + 2], k[(n - 1) * 4 + 3]}};
    }}
}}
"""
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(java)
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
